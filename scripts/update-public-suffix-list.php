<?php

declare(strict_types=1);

/**
 * Regenerates resources/public_suffix_list.php from Mozilla's Public Suffix List.
 *
 * Run before a release: `php scripts/update-public-suffix-list.php` (fetches
 * https://publicsuffix.org/list/public_suffix_list.dat), or pass a local copy
 * of the list as the first argument. The output is a plain PHP array, so the
 * runtime only `require`s it (opcache-friendly, no parsing per request).
 * IDN rules are converted to their ASCII (punycode) form, which is how origins
 * arrive; this needs ext-intl when the script runs, not at runtime. Run
 * `vendor/bin/pint resources` afterwards to keep the file in the house style.
 */
$source = $argv[1] ?? 'https://publicsuffix.org/list/public_suffix_list.dat';
$list = file_get_contents($source);

if ($list === false || ! str_contains($list, '===BEGIN PRIVATE DOMAINS===')) {
    fwrite(STDERR, "Could not read a complete Public Suffix List from {$source}\n");
    exit(1);
}

if (! function_exists('idn_to_ascii')) {
    fwrite(STDERR, "ext-intl is required to convert IDN rules to ASCII\n");
    exit(1);
}

$rules = [];

// The u flag matters: byte-wise, \R also breaks on 0x85, a byte inside many CJK characters.
foreach (preg_split('/\R/u', $list) ?: [] as $line) {
    // A rule is the first whitespace-delimited token; comments start with `//`.
    $rule = strtok(trim($line), " \t");

    if ($rule === false || str_starts_with($rule, '//')) {
        continue;
    }

    $prefix = str_starts_with($rule, '!') ? '!' : (str_starts_with($rule, '*.') ? '*.' : '');
    $domain = substr($rule, strlen($prefix));
    $ascii = idn_to_ascii($domain, IDNA_DEFAULT, INTL_IDNA_VARIANT_UTS46);
    $rules[$prefix.strtolower($ascii === false ? $domain : $ascii)] = true;
}

ksort($rules);

$header = <<<'PHP'
<?php

declare(strict_types=1);

// Generated by scripts/update-public-suffix-list.php from Mozilla's Public Suffix List
// (https://publicsuffix.org/list/public_suffix_list.dat). Do not edit by hand.
//
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.

PHP;

file_put_contents(
    __DIR__.'/../resources/public_suffix_list.php',
    $header.'// Fetched: '.gmdate('Y-m-d')."\n\nreturn ".var_export($rules, true).";\n",
);

echo count($rules)." rules written.\n";
